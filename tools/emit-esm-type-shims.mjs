#!/usr/bin/env node
/**
 * Writes the `.d.mts` type shims that the `import` condition points at.
 *
 * `libs/core` and `libs/graphql` are dual-format packages with a single
 * declaration tree. The root has no `"type": "module"`, so every emitted
 * `.d.ts` is CJS-flavoured — correct for the `require` condition, and wrong
 * for the `import` one: pairing ESM JavaScript with CJS types is what
 * `@arethetypeswrong/cli` calls masquerading, and it breaks `node16`
 * resolution for consumers who are themselves ESM.
 *
 * Emitting a second, ESM-flavoured copy of the whole tree would double the
 * package for no new information. Instead each entry point gets a one-line
 * `.d.mts` that re-exports the CJS-flavoured declarations. ESM may import CJS,
 * so this direction is legal and TypeScript synthesises the named exports —
 * the reverse (a `.d.cts` importing ESM types) is the one that fails.
 *
 * The re-export is `export *`, which does not carry a default export. A
 * default on one of these barrels would therefore disappear silently, so the
 * script refuses to write a shim for a barrel that has one.
 *
 * Usage: node tools/emit-esm-type-shims.mjs <projectRoot> <entry> [entry...]
 *   entry is the emitted path without extension, e.g. `index`,
 *   `adapters/member-base`.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { basename, join } from 'node:path';

const [projectRoot, ...entries] = process.argv.slice(2);

if (!projectRoot || entries.length === 0) {
  console.error(
    'usage: node tools/emit-esm-type-shims.mjs <projectRoot> <entry> [entry...]',
  );
  process.exit(1);
}

for (const entry of entries) {
  const declaration = join(projectRoot, `${entry}.d.ts`);

  if (!existsSync(declaration)) {
    console.error(
      `emit-esm-type-shims: ${declaration} does not exist — build first.`,
    );
    process.exit(1);
  }

  if (/^\s*export\s+default\b/m.test(readFileSync(declaration, 'utf8'))) {
    console.error(
      `emit-esm-type-shims: ${declaration} has a default export, which ` +
        '`export *` does not re-export. Widen the shim before shipping it.',
    );
    process.exit(1);
  }

  writeFileSync(
    join(projectRoot, `${entry}.d.mts`),
    [
      '// Generated by tools/emit-esm-type-shims.mjs — do not edit.',
      '//',
      '// ESM-flavoured types for the `import` condition. The declarations',
      '// themselves live in the sibling .d.ts, which is CJS-flavoured because',
      '// this package has no "type": "module".',
      `export * from './${basename(entry)}.js';`,
      '',
    ].join('\n'),
  );
}
